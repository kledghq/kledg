#!/usr/bin/env node
/**
 * Copies .github/workflows/update-from-kledg.yml into
 * lib/updates/workflow-template.ts, so the "Mises à jour" page can install
 * the workflow in copies that lack it (the Vercel button may drop .github).
 * lib/updates/__tests__/workflow-template.test.ts fails when they differ.
 *
 *   node scripts/sync-update-workflow.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'

const source = readFileSync('.github/workflows/update-from-kledg.yml', 'utf8')
const out = `// Generated by scripts/sync-update-workflow.mjs from .github/workflows/update-from-kledg.yml. Do not edit.
export const UPDATE_WORKFLOW = ${JSON.stringify(source)}
`
writeFileSync('lib/updates/workflow-template.ts', out)
