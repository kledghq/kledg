/**
 * Coverage of the API by the MCP server (docs/mcp.md, "Inventaire de l'API").
 *
 * The owner's rule: every action a user can do in Kledg can be done through
 * the MCP server, at the right level, with the same permission checks as
 * the route. Each handler of app/api (method and path) maps to the MCP
 * tools that do what it does, or to a written reason why it stays out of
 * the server. A guard test (lib/mcp/__tests__/route-coverage.test.ts) fails
 * when a route has no entry, when an entry names a tool that does not
 * exist, or when an entry is left for a route that is gone.
 *
 * Reasons are French (they are copied into docs/mcp.md).
 */

export type RouteCoverage =
  /** MCP tools doing what the handler does (several when the route combines steps). */
  | { tools: readonly string[]; note?: string }
  /** Why the handler stays out of the MCP server. */
  | { excluded: ExclusionReason }

