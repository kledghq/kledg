/**
 * The MCP tools that closed the last parity gaps (lib/mcp/route-coverage.ts):
 * file exports, Qonto statements and documents, the SIREN lookup and the
 * company lifecycle. Against PostgreSQL, called through the real /api/mcp
 * handler with API keys of each level (session mocked; Better Auth,
 * services, row level security and audit log real), with Qonto and the
 * company directory answered by a stubbed fetch (no network):
 * - each tool exists at its level and above, never below;
 * - a company outside the key's grant, or of which the user is not a
 *   member, is "Société introuvable"; an object of another company
 *   (fiscal year, receipt, invoice) is "introuvable";
 * - a viewer cannot export (reports:export) nor use a full control tool;
 * - files come back as an embedded resource (base64 blob, MIME type, file
 *   name) generated by the route's service, never with a URL;
 * - company creation follows the instance policy (and its hook), needs a
 *   grant of every company, and follows the execution mode (approval in
 *   Kledg with a pending action without company);
 * - archiving makes a company read-only and hides it, restoring reverses it,
 *   for instance administrators only.
 *
 * Run with KLEDG_RLS=enforce too (docs/rls.md). Skipped when the test
 * database server is unreachable.
 */

